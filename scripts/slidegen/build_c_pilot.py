# -*- coding: utf-8 -*-
"""
C科目（企業経営理論）のパイロット版スライドを生成するスクリプト。

docs/textbook/C_business_administration_textbook.md の内容から、
12種類の図解パターン（diagrams.py）をひととおり使う代表論点を選んで
スライド化した試作デッキ。テンプレートの見た目・使い勝手を確認するための
パイロットであり、C科目の全42論点を網羅するものではない。

実行方法：
    cd /home/user/SMEC && python3 -m scripts.slidegen.build_c_pilot

出力：
    slides/1st_stage/C_business_administration_pilot.pptx
"""

import os
from pptx.util import Pt

from . import theme as th
from . import diagrams as dg

OUT_DIR = os.path.join(os.path.dirname(__file__), "..", "..", "slides", "1st_stage")
OUT_PATH = os.path.join(OUT_DIR, "C_business_administration_pilot.pptx")

SUBJECT_TAG = "C. 企業経営理論"


def build():
    prs = th.new_presentation()

    # 1. 表紙
    dg.title_slide(
        prs,
        main_title="企業経営理論",
        subtitle="中小企業診断士 第1次試験 対策スライド（パイロット版）",
        subject_tag=SUBJECT_TAG,
    )

    # 2. 目次（アジェンダ）
    dg.bullet_slide(
        prs, "はじめに", "本デッキで扱う内容", SUBJECT_TAG,
        [
            "第1部：経営戦略論 — VRIO分析／PPM／5フォース分析／ひっかけポイント（VRIO）",
            "第2部：組織論 — 組織構造の比較／組織のライフサイクル／モチベーション理論（マズロー）",
            "第3部：マーケティング論 — STP／プロダクト・ライフサイクル（PLC）",
            ("本デッキは全12種類の図解パターンをC科目の代表論点で試作したものです", 1),
            ("各論点の詳細解説は docs/textbook/C_business_administration_textbook.md を参照してください", 1),
        ],
    )

    # --- 第1部：経営戦略論 -----------------------------------------------
    dg.section_header(
        prs, "第1部", "経営戦略論",
        "企業がどの事業に、どのように経営資源を配分し、競争に勝つかを考える分野。",
    )

    # C-1：VRIO分析（用語定義カード）
    dg.concept_definition(
        prs, "C-1：戦略の考え方・階層別戦略・VRIO", "VRIO分析", SUBJECT_TAG,
        keyword="VRIO\n分析",
        definition="自社の経営資源が競争力の源泉になっているかを、V（価値）・R（希少性）・"
                    "I（模倣困難性）・O（組織）の4つの視点でチェックする分析枠組み。"
                    "4つすべてが揃って初めて「持続的な競争優位」が実現する。",
        example="三代続く和菓子屋の「職人の技」：おいしい和菓子が作れる（価値）、他店にはない技術（希少性）、"
                "何十年もかけないと習得できない（模倣困難性）、技を商品化・販売できる体制がある（組織）"
                "→ 4つすべて揃い、持続的な競争優位が実現している。",
    )

    # C-1：ひっかけポイント（警告ボックス）
    dg.caution_box(
        prs, "C-1：戦略の考え方・階層別戦略・VRIO", "ひっかけポイント：模倣困難性を高める要因", SUBJECT_TAG,
        misconception="「価値の源泉が業界に知れ渡っている」「代替できる資源が外部から容易に調達できる」"
                      "状態は、模倣困難性を高める要因である。",
        correct="上記2つはむしろ模倣困難性を弱める要因。模倣困難性を高める要因として問われるのは"
                "「長い歴史の積み重ね（経路依存性）」や「因果関係の曖昧さ（なぜ強いのか他社にはわからない）」。",
        note="過去問で確認する：problem_sets/1st_stage/exercises/C_business_administration_exercises.md「C-1：戦略の考え方・VRIO」",
    )

    # C-4：PPM（2×2マトリクス）
    dg.matrix_2x2(
        prs, "C-4：企業戦略：PPM（プロダクト・ポートフォリオ・マネジメント）",
        "PPM：4つの事業ポジション", SUBJECT_TAG,
        x_label="市場シェア（相対市場シェア）　高←　　　→低",
        y_label="市場成長率　高←　　　→低",
        quadrants={
            'tl': ("花形（スター）", "稼ぐが投資も必要。将来の主力候補"),
            'tr': ("問題児", "将来性はあるが今は稼げない。育てるか撤退か判断が必要"),
            'bl': ("金のなる木（キャッシュカウ）", "あまり投資が要らず安定して稼ぐ。他事業の資金源"),
            'br': ("負け犬", "稼げず将来性も薄い。撤退候補"),
        },
    )

    # C-6：5フォース分析（ハブ&スポーク）
    dg.hub_and_spoke(
        prs, "C-6：競争戦略：業界の構造分析", "5フォース分析（M.ポーター）", SUBJECT_TAG,
        hub_text="業界の\n収益性",
        spokes=[
            "既存競合の脅威\n（同業他社との競争）",
            "新規参入の脅威\n（参入障壁の高さ）",
            "代替品の脅威\n（異業種の代替手段）",
            "売り手の交渉力\n（仕入先の力）",
            "買い手の交渉力\n（顧客の力）",
        ],
    )

    # --- 第2部：組織論 -----------------------------------------------------
    dg.section_header(
        prs, "第2部", "組織論",
        "会社をどのような構造・文化・人の動機づけで運営するかを考える分野。",
    )

    # C-16：組織構造の比較（比較表）
    dg.comparison_table(
        prs, "C-16：組織構造の形態", "職能別組織 vs 事業部制組織", SUBJECT_TAG,
        col_a_title="職能別組織", col_b_title="事業部制組織",
        row_labels=["特徴", "メリット", "デメリット"],
        rows=[
            ("「営業部」「製造部」など機能ごとに部門化", "「A事業部」「B事業部」など製品・地域ごとに部門化。各事業部が損益に責任を持つ"),
            ("専門性が高まる、効率的", "事業ごとの意思決定が速い、経営者的な人材が育ちやすい"),
            ("部門間の連携が悪くなりがち、全社的視点の人材が育ちにくい", "機能の重複（各事業部にそれぞれ営業・経理）でコストがかさむ"),
        ],
    )

    # C-24：組織のライフサイクル（循環図）
    dg.cycle_diagram(
        prs, "C-24：組織変革と組織成長", "組織のライフサイクル", SUBJECT_TAG,
        steps=["創業期\n(資金調達が課題)", "成長期\n(仕組み化が課題)", "成熟期\n(硬直化への対応)", "衰退・再生期\n(再生か縮小か)"],
    )

    # C-19：マズローの欲求段階説（ピラミッド）
    dg.pyramid(
        prs, "C-19：組織における個人：モチベーション理論", "マズローの欲求段階説", SUBJECT_TAG,
        levels=[
            ("自己実現欲求", "自分の能力・可能性を最大限発揮したいという欲求"),
            ("承認欲求", "他者から認められたい、尊敬されたいという欲求"),
            ("社会的欲求", "集団に所属したい、愛情を得たいという欲求"),
            ("安全欲求", "身体的・経済的な安全を確保したいという欲求"),
            ("生理的欲求", "食欲・睡眠など生命維持に必要な基本的欲求"),
        ],
    )

    # --- 第3部：マーケティング論 -------------------------------------------
    dg.section_header(
        prs, "第3部", "マーケティング論",
        "誰に・何を・どう売るかを考える分野。STPと4Pが基本フレームワーク。",
    )

    # C-31：STP（プロセスフロー）
    dg.process_flow(
        prs, "C-31：マーケティング計画と戦略", "STP：誰に売るかを決めるプロセス", SUBJECT_TAG,
        steps=[
            ("セグメンテーション", "市場を年齢・地域・ライフスタイル等の基準で細分化する"),
            ("ターゲティング", "細分化した市場（セグメント）の中から狙う市場を選ぶ"),
            ("ポジショニング", "選んだ市場で競合と比べた自社商品の独自の位置づけを明確にする"),
        ],
    )

    # C-36：プロダクト・ライフサイクル（タイムライン）
    dg.timeline(
        prs, "C-36：プロダクト・マネジメント：PLC、新製品開発", "プロダクト・ライフサイクル（PLC）", SUBJECT_TAG,
        milestones=[
            ("導入期", "販売量少、認知度が低い→製品の認知拡大に注力"),
            ("成長期", "販売量が急拡大、競合が参入→シェア拡大、販売網の拡大"),
            ("成熟期", "販売量がピークで伸びが鈍化→差別化、ブランド強化"),
            ("衰退期", "販売量が減少→撤退判断、または縮小継続"),
        ],
    )

    # フッター（ページ番号）を全スライドに追加
    total = len(prs.slides._sldIdLst)
    for i, slide in enumerate(prs.slides, start=1):
        th.add_footer(slide, i, total)

    os.makedirs(OUT_DIR, exist_ok=True)
    prs.save(OUT_PATH)
    print(f"Saved: {os.path.abspath(OUT_PATH)} ({total} slides)")


if __name__ == "__main__":
    build()
